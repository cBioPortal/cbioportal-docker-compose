#!/usr/bin/env python3
"""Export a complete, de-identified Databricks WSI snapshot for a study.

The portal study files define the cohort.  Databricks owns the canonical WSI
associations and thumbnail registry, so this exporter performs one bulk SQL
read, filters rows to the study's patient/sample identifiers, and writes the
portal ``meta_wsi.txt``/``data_wsi.txt`` contract.  It intentionally reads the
de-identified canonical table only; PHI tables are never queried.  Canonical
associations that are explicitly marked ``can_serve_tiles = false`` are kept
as non-servable provenance (including matched BLOCK/PART rows); only rows
marked servable are allowed to fail the complete-pixel contract.

Exports fail closed when Databricks marks a row as tile-servable but its
published registry record is missing source, thumbnail, or validated tile
metadata.  Explicitly non-servable associations remain in the hierarchy with
empty pixel fields so timeline counts and pathology provenance are preserved.
``--allow-incomplete-assets`` is reserved for diagnostics and must not be used
for an accepted study release.
"""

